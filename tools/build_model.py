def shield_texture():
    """Tileable, softly blurred water caustics pattern for the shield and cloak bubble.

    Sum of periodic waves (integer frequencies tile seamlessly); bright lines appear where the wave field
    crosses zero, like light on the floor of a pool. Black = invisible (additive).
    """
    N = 256
    rng = np.random.default_rng(7)
    yy, xx = np.mgrid[0:N, 0:N].astype(np.float32) / N
    def wave_field():
        f = np.zeros((N, N), np.float32)
        for _ in range(16):
            fx, fy = rng.integers(-5, 6, 2)
            if fx == 0 and fy == 0:
                continue
            f += np.cos(2 * math.pi * (fx * xx + fy * yy) + rng.uniform(0, 2 * math.pi)) / math.hypot(fx, fy) ** 0.7
        return f / np.abs(f).max()

    f1, f2 = wave_field(), wave_field()
    lines = np.exp(-(f1 / 0.08) ** 2) + np.exp(-(f2 / 0.08) ** 2) * 0.8   # caustics network
    glow = 0.3 + 0.2 * (f1 * f2)                                             # soft base haze
    k = lines * 0.6 + glow * 0.35
    # seamless blur: tile 3x3, blur, crop the center
    tile = Image.fromarray((np.clip(k, 0, 1) * 255).astype(np.uint8))
    big = Image.new('L', (N * 3, N * 3))
    for i in range(3):
        for j in range(3):
            big.paste(tile, (i * N, j * N))
    big = big.filter(ImageFilter.GaussianBlur(3.5)).crop((N, N, 2 * N, 2 * N))
    k = np.asarray(big, np.float32) / 255.0
    img = np.stack([90 * k, 185 * k, 255 * k], axis=-1)
    return Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), 'RGB')


